export function createSeedDB() {
  const base = Date.UTC(2026, 0, 1)
  const products = SEED_PRODUCTS.map((product, index) => ({
    ...product,
    createdAt: new Date(base + index * 86_400_000).toISOString(),
    updatedAt: new Date(base + index * 86_400_000).toISOString(),
  }))

  return {
    version: DB_VERSION,
    products,
    categories: SEED_CATEGORIES.map((category) => ({ ...category })),
  }
}
